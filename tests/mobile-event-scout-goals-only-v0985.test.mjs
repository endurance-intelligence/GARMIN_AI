import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8')

test('Goals is the sole owner of event administration and archived race sources',()=>{
 const goals=read('src/pages/GoalsPage.tsx')
 const scout=read('src/components/RaceEventResearch.tsx')
 const race=read('src/pages/RacePage.tsx')
 assert.match(goals,/<details className="goals-event-scout"/)
 assert.match(goals,/Veranstaltungsdaten &amp; Wettkampfarchiv/)
 assert.match(goals,/<RaceEventResearch active=\{active&&showEventScout\}/)
 assert.match(goals,/onEventSaved=\{changed\}/)
 assert.match(scout,/GOALS \/ EVENT SCOUT/)
 assert.match(scout,/WETTKAMPFARCHIV/)
 assert.match(scout,/Website analysieren/)
 assert.match(scout,/Gespeicherte Veranstaltungsdaten/)
 assert.match(scout,/Komoot-Link ändern/)
 assert.doesNotMatch(race,/RaceEventResearch|Website analysieren|WETTKAMPFARCHIV|Gespeicherte Veranstaltungsdaten/)
})
test('Race Prep keeps forecast, map and actual race strategy, not goal management',()=>{
 const race=read('src/pages/RacePage.tsx')
 const dossier=read('src/components/RaceEventDossier.tsx')
 assert.match(race,/<RaceStrategyCard active=\{active\} onCoach=\{\(\)=>onGo\('home'\)\}/)
 assert.match(race,/<RaceEventDossier active=\{active\}/)
 assert.match(race,/<RaceForecastCompact active=\{active\}/)
 assert.match(race,/<RaceRouteViewer active=\{active\}/)
 assert.match(race,/<\/RaceEventDossier>/)
 assert.match(dossier,/garmin-race-research/)
 assert.match(dossier,/const current=\(data\.saved\|\|\[\]\)\.find\(x=>x\.race_date===data\.goal\?\.raceDate\)/)
 assert.match(dossier,/typeof current\?\.details\?\.city==='string'/)
 assert.match(dossier,/onCourseChange\?\.\(/)
 assert.match(dossier,/Rennwetter, Streckenverlauf und Höhenprofil/)
 assert.match(dossier,/\{children\}/)
 assert.doesNotMatch(dossier,/onClick=|\.upsert\(|action:'save'|Website analysieren/)
})
test('weather deeplink remains functional when event metadata is saved only in Goals',()=>{
 const app=read('src/App.tsx')
 const race=read('src/pages/RacePage.tsx')
 const forecast=read('src/components/RaceForecastCompact.tsx')
 assert.match(app,/function openRaceWeather\(\)/)
 assert.match(race,/getElementById\('race-detailed-forecast'\)/)
 assert.match(forecast,/id="race-detailed-forecast" tabIndex=\{-1\}/)
 assert.doesNotMatch(race,/setResearchRefresh|onEventSaved/)
})
test('event editor remains stateful while collapsed and does not unexpectedly rewrite a goal',()=>{
 const goals=read('src/pages/GoalsPage.tsx')
 const scout=read('src/components/RaceEventResearch.tsx')
 assert.match(goals,/showEventScout&&<RaceEventResearch/)
 assert.match(scout,/sessionStorage\.setItem\(cacheKey\(goal\.raceDate\)/)
 assert.match(scout,/sessionStorage\.getItem\(cacheKey\(date\)/)
 assert.match(scout,/trainingGoalChanged:false|persönliches Trainingsziel bleibt unverändert/)
 assert.doesNotMatch(read('src/components/RaceEventDossier.tsx'),/sessionStorage\.setItem|update\(|\\.upsert\(/)
})
