import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')

test('athlete navigates from selected calendar day to exactly that Coach day',()=>{
 const app=read('src/App.tsx')
 const calendar=read('src/pages/CalendarPage.tsx')
 const home=read('src/pages/CoachPage.tsx')
 const coach=read('src/components/CoachSevenDay.tsx')
 assert.match(app,/function openCoach\(date\?:string\)/)
 assert.match(app,/setCoachFocus\(prev=>\(\{date,token:/)
 assert.match(app,/<CalendarPage active=\{page==='calendar'\} focus=\{calendarFocus\} decisionFocus=\{coachFocus\} onOpenCoach=\{openCoach\}/)
 assert.match(app,/<CoachPage active=\{page==='home'\} onGo=\{go\}/)
 assert.match(calendar,/onOpenCoach:\(date\?:string\)=>void/)
 assert.match(calendar,/onOpenCoach\(selected\)/)
 assert.match(calendar,/Vorschlag prüfen/)
 assert.match(calendar,/<CoachSevenDay key=[\s\S]*focus=\{decisionFocus\}/)
 assert.match(coach,/setSelectedDay\(focus.date\)/)
 assert.match(coach,/plan.days.some\(day=>day.date===focus.date\)/)
 assert.match(coach,/lastFocus.current===focus.token/)
})
