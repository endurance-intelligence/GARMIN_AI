import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')

test('Coach race weather is a real focusable control, not inert decorative data',()=>{
 const mini=read('src/components/CoachRaceWeatherMini.tsx')
 const goal=read('src/components/CoachGoalPanel.tsx')
 const coach=read('src/pages/GoalsPage.tsx')
 assert.match(mini,/return <button type="button" className="cg-home-weather"/)
 assert.match(mini,/onClick=\{onOpenDetails\}/)
 assert.match(mini,/disabled=\{!onOpenDetails\}/)
 assert.match(mini,/aria-label=\{'Detaillierte Rennwetterprognose/)
 assert.match(mini,/cg-home-weather-open/)
 assert.match(goal,/onForecastOpen\?:\(\)=>void/)
 assert.match(goal,/onOpenDetails=\{onForecastOpen\}/)
 assert.match(coach,/onOpenRaceWeather\?:\(\)=>void/)
 assert.match(coach,/onForecastOpen=\{onOpenRaceWeather\}/)
})
test('one tap switches Race Prep and focuses the detailed weather section',()=>{
 const app=read('src/App.tsx')
 const race=read('src/pages/RacePage.tsx')
 const forecast=read('src/components/RaceForecastCompact.tsx')
 assert.match(app,/const \[raceWeatherFocus,setRaceWeatherFocus\]=useState\(0\)/)
 assert.match(app,/function openRaceWeather\(\)/)
 assert.match(app,/setRaceWeatherFocus\(n=>n\+1\)/)
 assert.match(app,/go\('race'\)/)
 assert.match(app,/onOpenRaceWeather=\{openRaceWeather\}/)
 assert.match(app,/focusWeatherToken=\{raceWeatherFocus\}/)
 assert.match(race,/getElementById\('race-detailed-forecast'\)/)
 assert.match(race,/scrollIntoView\(\{behavior:'smooth',block:'start'\}\)/)
 assert.match(race,/target\.focus\(\{preventScroll:true\}\)/)
 assert.match(race,/lastWeatherFocus\.current=focusWeatherToken/)
 assert.match(forecast,/id="race-detailed-forecast" tabIndex=\{-1\}/)
})
