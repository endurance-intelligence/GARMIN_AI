import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8')
test('shoe photo GET never lists Storage objects or signs N URLs sequentially',()=>{
 const code=read('supabase/functions/garmin-gear-image/index.ts')
 assert.match(code,/storage\.createSignedUrls\(/)
 assert.doesNotMatch(code,/storage\.list\('gear'/)
 assert.doesNotMatch(code,/storage\.createSignedUrl\(/)
 assert.match(code,/requested\.map\(x=>x\.path\),3600/)
 assert.match(code,/signedUrl/)
 assert.match(code,/eligible\.entries\(\)/)
 assert.match(code,/auth\.auth\.getUser\(match\[1\]\)/)
 assert.match(code,/user\.email_confirmed_at/)
 assert.match(code,/createClient\(projectUrl,envKey\('secret'\)/)
})
test('private shoe photos are not made public and uploads remain guarded',()=>{
 const code=read('supabase/functions/garmin-gear-image/index.ts')
 assert.match(code,/isActiveRunningShoe/)
 assert.match(code,/normalizedGearImageId/)
 assert.match(code,/image\/webp/)
 assert.match(code,/upsert:true/)
 assert.doesNotMatch(code,/getPublicUrl\(/)
 assert.match(code,/return json\(\{images\},200,headers\)/)
})
test('image UI provides a retry without losing stored gear or deleting a photo',()=>{
 const view=read('src/components/GarminConnectSnapshot.tsx')
 assert.match(view,/const \[imageReload,setImageReload\]=useState\(0\)/)
 assert.match(view,/setImageReload\(v=>v\+1\)/)
 assert.match(view,/fetchShoeImages\(session\)/)
 assert.match(view,/imageLoading/)
 assert.match(view,/Bilder neu laden/)
 assert.match(view,/setShoeImages\(old=>/)
 assert.match(read('src/lib/gearImages.ts'),/Deine Fotos sind weiterhin gespeichert/)
 assert.match(view,/mode==='gear'/)
})
test('Coach today uses a deliberately styled, finger-sized button and concise information',()=>{
 const view=read('src/components/CoachGlance.tsx')
 const css=read('src/styles/coach-glance.css')
 assert.match(view,/Kalender öffnen <Icon name="arrow-up-right"/)
 assert.match(view,/Heute noch offen/)
 assert.doesNotMatch(view,/Den 7-Tage-Vorschlag findest du weiter unten/)
 assert.match(css,/\.co-home \.co-link\{/)
 assert.match(css,/min-height:44px;min-width:155px/)
 assert.match(css,/\.co-home \.co-section-head\{display:flex/)
 assert.match(css,/\.co-home \.co-today\{/)
 assert.match(css,/@media\(max-width:600px\)/)
 assert.match(view,/!loading&&view\?\.availabilityOk&&!view\.blocked&&children/)
})
