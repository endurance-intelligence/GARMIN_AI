import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {
 activeGarminCooldown,retryAfterLimit,clearedGarminCooldown
} from '../supabase/functions/_shared/garmin-cloud-backoff.mjs'
const source=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8')
const start='2026-11-12T18:00:00.000Z'
const ms=(d)=>Date.parse(d)
test('first 429 backs off for exactly 24 hours; schedule checks do NOT extend it',()=>{
 const row=retryAfterLimit({consecutive_429:0,retry_after:null},start)
 assert.equal(row.retry_after,'2026-11-13T18:00:00.000Z')
 assert.equal(row.consecutive_429,1)
 assert.equal(activeGarminCooldown(row,'2026-11-12T21:00:00Z'),true)
 assert.equal(activeGarminCooldown(row,row.retry_after),false)
 const duplicate=retryAfterLimit(row,'2026-11-12T21:00:00Z')
 assert.equal(duplicate.retry_after,row.retry_after)
 assert.equal(duplicate.consecutive_429,1)
})
test('repeated real Garmin 429s back off 48, then capped 72 hours',()=>{
 const a=retryAfterLimit({},start)
 const b=retryAfterLimit(a,'2026-11-13T18:01:00Z')
 assert.equal(ms(b.retry_after)-ms('2026-11-13T18:01:00Z'),48*3600000)
 assert.equal(b.consecutive_429,2)
 const c=retryAfterLimit(b,'2026-11-15T18:02:00Z')
 assert.equal(ms(c.retry_after)-ms('2026-11-15T18:02:00Z'),72*3600000)
 assert.equal(c.consecutive_429,3)
 const d=retryAfterLimit(c,'2026-11-18T18:03:00Z')
 assert.equal(d.consecutive_429,3)
 assert.equal(ms(d.retry_after)-ms('2026-11-18T18:03:00Z'),72*3600000)
})
test('only confirmed successful Garmin reconciliation resets 429 history',()=>{
 const previous=retryAfterLimit({},start)
 const next=clearedGarminCooldown('2026-11-13T18:01:00Z')
 assert.equal(next.retry_after,null)
 assert.equal(next.consecutive_429,0)
 assert.equal(next.last_success_at,'2026-11-13T18:01:00Z')
 assert.equal(activeGarminCooldown(next,'2026-11-13T18:01:00Z'),false)
 assert.notDeepEqual(next,previous)
})
test('private persistent cooldown table denies direct user and anonymous access',()=>{
 const sql=source('supabase/migrations/20261112173000_garmin_cloud_oauth_backoff.sql')
 assert.match(sql,/create table if not exists public\.garmin_cloud_backoff/)
 assert.match(sql,/enable row level security/)
 assert.match(sql,/revoke all on table public\.garmin_cloud_backoff from anon, authenticated/)
 assert.match(sql,/grant select, insert, update on table public\.garmin_cloud_backoff to service_role/)
 assert.doesNotMatch(sql,/access_token|refresh_token/i)
})
test('OIDC worker denies Garmin token handout during active cooldown, no caller-controlled expiry',()=>{
 const worker=source('supabase/functions/garmin-cloud-worker/index.ts')
 assert.match(worker,/trustedGarminWorkerClaims\(payload\)/)
 assert.match(worker,/jwtVerify\(match\[1\],jwks/)
 assert.match(worker,/activeGarminCooldown\(gate\.data\)/)
 const checkpoint=worker.indexOf("if(activeGarminCooldown(gate.data))")
 const tokenread=worker.indexOf("db.rpc('garmin_connect_session_get')")
 assert.ok(checkpoint>=0&&tokenread>checkpoint)
 assert.match(worker,/deferred:true,reason:'garmin-rate-limit'/)
 assert.match(worker,/value\.action==='record-rate-limit'/)
 assert.match(worker,/retryAfterLimit\(previous\.data\)/)
 assert.match(worker,/!\['oauth-refresh','activity-gear','full-audit'\]\.includes/)
 assert.match(worker,/\.update\(clearedGarminCooldown\(\)\)/)
})
test('both scheduled and manual audit respect the gate and report 429 via owner OIDC only',()=>{
 const runner=source('scripts/cloud/sync-garmin-gear.mjs')
 const audit=source('scripts/cloud/audit-garmin-connect.mjs')
 assert.match(runner,/if\(credentials\?\.deferred===true\)/)
 assert.match(runner,/recordGarmin429\(jwt,'oauth-refresh',e\)/)
 assert.match(runner,/recordGarmin429\(jwt,'activity-gear',e\)/)
 assert.match(runner,/action:'record-rate-limit',phase/)
 assert.match(audit,/if\(credential\?\.deferred===true\)/)
 assert.match(audit,/action:'record-rate-limit',phase:'full-audit'/)
 assert.match(runner,/client\.refreshTokens\(\)/)
 assert.match(runner,/getActivityGear\(activity\.activityId\)/)
 assert.doesNotMatch(runner,/getGearActivities\(|addGearToActivity\(|removeGearFromActivity\(/)
 assert.doesNotMatch(runner,/console\.log\([^\n]*(credentials\.tokens|jwt|access_token)/)
})
