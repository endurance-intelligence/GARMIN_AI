import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {previousOrcFlyer} from '../src/lib/workoutLibrary.ts'
const read=x=>readFileSync(new URL('../'+x,import.meta.url),'utf8')
const page=read('src/components/WorkoutArchivePanel.tsx')
const modal=read('src/components/WorkoutReviewDialog.tsx')
const css=read('src/styles/workout-review-dialog.css')

test('training review is one portaled accessible dialog, not nested layers',()=>{
 assert.match(page,/import \{WorkoutReviewDialog\} from '.\/WorkoutReviewDialog'/)
 assert.match(page,/<WorkoutReviewDialog/)
 assert.match(modal,/createPortal\(/)
 assert.match(modal,/role="dialog" aria-modal="true"/)
 assert.match(modal,/document\.body\.style\.overflow='hidden'/)
 assert.match(modal,/event\.key==='Escape'/)
 assert.match(modal,/event\.key!=='Tab'/)
 assert.doesNotMatch(page,/<div className="wa-editor">|<details className="wa-local-photo">/)
 assert.doesNotMatch(modal,/<details(?:\s|>)/)
})
test('all five reviewed ORC groups can be chosen in one single modal',()=>{
 const w=previousOrcFlyer()
 assert.deepEqual(w.groups.map(g=>g.name),['Fuchs','Wolf','Tiger','Bären','Capybara'])
 assert.match(page,/const \[referenceConfirmed,setReferenceConfirmed\]=useState\(false\)/)
 assert.match(page,/if\(!referenceConfirmed\|\|!localPhotoUrl\|\|!ocrRaw\)return/)
 assert.match(page,/begin\(previousOrcFlyer\(\),'trainer_photo',imageHash\)/)
 assert.match(modal,/Alle 5 Gruppen übernehmen/)
 assert.match(modal,/Ich bestätige, dass es dieselbe ORC-Grafik ist/)
 assert.match(modal,/workout\.groups\.map\(\(g,i\)=>/)
 assert.match(modal,/onGroup\(i\)/)
 assert.match(modal,/groupIndex===i/)
 assert.match(modal,/einzelne Garmin-Schritte/)
})
test('unreliable OCR remains clearly identified and does not fabricate missing groups',()=>{
 assert.match(page,/setOcrIdentifiedGroups\(interpreted.detectedGroups\)/)
 assert.match(modal,/Lokale Texterkennung: '\+ocrIdentifiedGroups/)
 assert.match(modal,/Die lokale Texterkennung liest die Grafik nicht vollständig/)
 assert.match(modal,/Die lokale Texterkennung liest die Grafik nicht vollständig/)
})
test('group has direct summary and interval sequence without nested accordions',()=>{
 assert.match(modal,/pane==='overview'/)
 assert.match(modal,/pane==='track'/)
 assert.match(modal,/pane==='edit'/)
 assert.match(modal,/group\.steps\.map\(\(step,i\)=>/)
 assert.match(modal,/makeTrackLapGuide\(workout,group.name\)/)
 assert.match(modal,/wr-interval-run/)
 assert.match(css,/\.wr-interval\{display:grid/)
 assert.match(css,/@media\(max-width:760px\)/)
 assert.match(css,/safe-area-inset-bottom/)
})
test('review gate and protected owner-only archive save remain unchanged',()=>{
 assert.match(modal,/Ich habe die Trainerangaben und alle Gruppen geprüft/)
 assert.match(modal,/disabled=\{busy\|\|localBusy\|\|!approved\}/)
 assert.match(page,/action:'save',clientRequestId:requestId.current,reviewed:true/)
 assert.match(page,/workout:editing,sourceKind,sourceImageSha256:imageHash/)
 assert.match(page,/action:'plan',templateId:template.id,group,date/)
 assert.doesNotMatch(page,/scheduleWorkout\(|uploadWorkout\(|addWeighIn\(/)
 assert.match(read('src/App.tsx'),/<OnlineAccessGate>/)
})
test('archived training preview opens same dialog rather than an inline expanded list',()=>{
 assert.match(page,/onClick=\{\(\)=>viewRecord\(record,group\)\}/)
 assert.match(page,/setPreviewRecord\(record\);setReviewOpen\(true\)/)
 assert.match(modal,/Für \{date\.split/)
 assert.match(modal,/Als neue Version bearbeiten/)
 assert.doesNotMatch(page,/className="wa-record-details"|setExpanded\(/)
})
