import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const edge=read('supabase/functions/garmin-cloud-worker/index.ts')
const runner=read('scripts/cloud/sync-garmin-gear.mjs')
const claims=read('supabase/functions/_shared/garmin-worker-claims.mjs')
const workflow=read('.github/workflows/garmin-cloud-audit.yml')
const ui=read('src/components/GarminConnectSnapshot.tsx')
test('secret tokens remain behind exactly authenticated OIDC main-branch job',()=>{
 assert.match(edge,/jwtVerify\(match\[1\],jwks/)
 assert.match(edge,/trustedGarminWorkerClaims\(payload\)/)
 assert.match(edge,/if\(req\.headers\.has\('origin'\)\)/)
 assert.match(claims,/payload\.ref==='refs\/heads\/main'/)
 assert.match(claims,/payload\.workflow_ref==='endurance-intelligence\/GARMIN_AI\/\.github\/workflows\/garmin-cloud-audit\.yml@refs\/heads\/main'/)
 assert.match(claims,/payload\.event_name==='schedule'/)
 assert.match(runner,/ACTIONS_ID_TOKEN_REQUEST_TOKEN/)
 assert.doesNotMatch(runner,/SUPABASE_SERVICE_ROLE_KEY|GARMIN_API_KEY/)
})
test('runner reads ONLY per-activity gear, never writes back to Garmin or shares raw tokens',()=>{
 assert.match(runner,/getActivityGear\(activity\.activityId\)/)
 assert.match(runner,/readActivityGear\(raw,credentials\.baseline\.gear\)/)
 assert.match(runner,/client\.refreshTokens\(\)/)
 assert.match(runner,/tokenChanged\(credentials\.tokens,after\)/)
 assert.match(runner,/action:'incremental-gear'/)
 assert.doesNotMatch(runner,/getGearActivities\(|addGearToActivity\(|removeGearFromActivity\(|setGear|createGear|deleteGear/)
 assert.doesNotMatch(runner,/console\.log\([^\n]*(credential\.tokens|raw|jwt|access_token)/)
})
test('new owner-only bridge accepts a bounded set of Garmin-confirmed running IDs',()=>{
 assert.match(edge,/value\.action==='incremental-gear'/)
 assert.match(edge,/mergeActivityGear\(current\.data\.activity_gear,current\.data\.gear,reports\)/)
 assert.match(edge,/runningSport\(a\.sport_type\)/)
 assert.match(edge,/reports\.length>30/)
 assert.match(edge,/new Set\(ids\)\.size!==ids\.length/)
 assert.match(edge,/if\(current\.data\.synced_at!==expected\)/)
 assert.match(edge,/\.eq\('synced_at',expected\)/)
 assert.match(edge,/gear_links_checked_at:when/)
 assert.match(edge,/garminWritten:false/)
 assert.match(edge,/selectActivityTargets\(/)
 assert.match(edge,/\.gte\('start_time_local',since\)/)
})
test('scheduled job stays on main, with explicit 3-hour cadence and no privileged github secrets',()=>{
 assert.match(workflow,/cron: '37 \*\/3 \* \* \*'/)
 assert.match(workflow,/github\.ref == 'refs\/heads\/main'/)
 assert.match(workflow,/id-token: write/)
 assert.match(workflow,/persist-credentials: false/)
 assert.match(workflow,/node scripts\/cloud\/sync-garmin-gear\.mjs/)
 assert.match(workflow,/inputs\.task == 'full-audit'/)
 assert.doesNotMatch(workflow,/pull_request:/)
})
test('Equipment can re-read confirmed distances without a fake immediate Garmin sync',()=>{
 assert.match(ui,/snapshotRefresh,setSnapshotRefresh/)
 assert.match(ui,/window\.addEventListener\('focus',onFocus\)/)
 assert.match(ui,/5\*60\*1000/)
 assert.match(ui,/automatische Cloud-Prüfung alle 3 Stunden eingerichtet/)
 assert.match(ui,/Schuhzuordnungen: \$\{formatDate\(snapshot\.gear_links_checked_at\)\}/)
 assert.match(ui,/Anzeige aktualisieren/)
 assert.match(read('src/pages/GearPage.tsx'),/mode="gear" active=\{active\}/)
})

test('a verified cloud refresh is persisted as distinct from a manual gear import',()=>{
 const worker=read('supabase/functions/garmin-cloud-worker/index.ts')
 const snapshot=read('supabase/functions/garmin-connect-snapshot/index.ts')
 const status=read('supabase/functions/garmin-sync-center/index.ts')
 const view=read('src/components/SyncCenter.tsx')
 const migration=read('supabase/migrations/20261112153500_garmin_cloud_gear_sync_source.sql')
 assert.match(migration,/gear_links_sync_source text not null default 'manual'/)
 assert.match(worker,/gear_links_sync_source:'cloud'/)
 assert.match(snapshot,/gear_links_sync_source:'manual'/)
 assert.match(snapshot,/gear_links_checked_at,gear_links_sync_source/)
 assert.match(status,/gearSource==='cloud'/)
 assert.match(status,/syncSource:gearSource/)
 assert.match(view,/gearFromCloud=data\?\.sources\.equipment\.syncSource==='cloud'/)
 assert.match(view,/Laufschuhe · Garmin-Cloud-Abgleich/)
 assert.match(view,/Garmin-Ausrüstung · bisheriger Import/)
})
