import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8')
const calendar=read('src/pages/CalendarPage.tsx')
const css=read('src/styles/horizon-calendar.css')
const api=read('supabase/functions/garmin-training-plan/index.ts')
const intervals=read('supabase/functions/garmin-intervals/index.ts')
test('backend still checks owner, illness, blocked days and explicit calendar approval',()=>{
 assert.match(api,/user\.email_confirmed_at/)
 assert.match(api,/coachWorkoutAllowed\(context,input\.kind,input\.date\)/)
 assert.match(api,/coachWorkoutAllowed\(context,source\.coachKind,current\.training_date\)/)
 assert.match(intervals,/plan\.state!=='pending'\|\|!plan\.approved_at/)
 assert.match(intervals,/coachWorkoutAllowed\(context,/)
 assert.match(intervals,/validateStoredIntervalsWorkout\(found,plan\.archive_snapshot,event\)/)
 assert.doesNotMatch(calendar,/getActivityGear\(|garminconnect-js|garmin-connect\.com/)
})
test('successful Intervals POST remains confirmed if separate status GET fails',()=>{
 assert.match(api,/intervals_sync_status,intervals_export_version,archive_snapshot,created_at/)
 assert.match(calendar,/intervals_export_version:number\|null/)
 assert.match(calendar,/published\[plan\.id\]\|\|\{/)
 assert.match(calendar,/intervals_sync_status:plan\.intervals_sync_status/)
 assert.match(calendar,/intervals_export_version:plan\.intervals_export_version/)
 assert.match(calendar,/async function publishPlan\(plan:Plan\)/)
 assert.match(calendar,/Browser network errors do not prove that a remote write failed/)
 assert.match(calendar,/const verified=fresh\.entries\?\.find\(p=>p\.id===plan\.id/)
 assert.match(calendar,/setPlans\(old=>old\.map\(p=>p\.id===plan\.id\?verified:p\)\)/)
 assert.match(calendar,/Status noch unklar\. Bitte erst Kalender aktualisieren, nicht erneut senden/)
})
test('individual approval and publishing remain available after removing the batch UI',()=>{
 assert.doesNotMatch(calendar,/<details className="hc-week-planner"/)
 assert.doesNotMatch(calendar,/async function (approveCoachWeek|publishCoachWeek)/)
 assert.match(css,/min-height:44px/)
 assert.match(css,/@media\(max-width:600px\)/)
 assert.match(calendar,/async function acceptCoach\(day:CoachDay,quick=false\)/)
 assert.match(calendar,/async function approvePlan\(plan:Plan\)/)
 assert.match(calendar,/async function publishPlan\(plan:Plan\)/)
})
