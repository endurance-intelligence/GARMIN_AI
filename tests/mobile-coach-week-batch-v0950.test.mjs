 assert.match(calendar,/const coachDrafts=plans\.filter\(p=>p\.training_date>=today/)
 assert.match(calendar,/const weekSelectedDrafts=coachDrafts\.filter/)
 assert.match(calendar,/weekApprovalCount=weekSelected\.length\+weekSelectedDrafts\.length/)
 assert.match(calendar,/for\(const draft of weekSelectedDrafts\)/)
 assert.match(calendar,/action:'approve',id:draft\.id,revision:draft\.revision/)
 assert.match(calendar,/gespeicherter Entwurf · noch nicht freigegeben/)
